import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cssName, legacyAliases, scales, themeEffects, themes, type ThemeName } from './tokens.js';

const decl = (name: string, value: string) => `  --${name}: ${value};`;

function themeBlock(name: ThemeName): string {
  const lines = [
    ...Object.entries(themes[name]).map(([k, v]) => decl(cssName(k), v)),
    ...Object.entries(themeEffects[name]).map(([k, v]) => decl(cssName(k), v)),
    `  color-scheme: ${name};`,
  ];
  return lines.join('\n');
}

function scaleBlock(): string {
  const out: string[] = [];
  for (const [k, v] of Object.entries(scales.space)) out.push(decl(`space-${k}`, v));
  for (const [k, v] of Object.entries(scales.radius)) out.push(decl(`radius-${k}`, v));
  for (const [k, v] of Object.entries(scales.duration)) out.push(decl(`dur-${k}`, v));
  for (const [k, v] of Object.entries(scales.ease)) out.push(decl(`ease-${cssName(k)}`, v));
  for (const [k, v] of Object.entries(scales.z)) out.push(decl(`z-${k}`, v));
  for (const [k, [size, line]] of Object.entries(scales.text)) {
    out.push(decl(`text-${k}`, size), decl(`leading-${k}`, line));
  }
  for (const [k, v] of Object.entries(scales.weight)) out.push(decl(`weight-${k}`, v));
  for (const [k, v] of Object.entries(scales.font)) out.push(decl(`font-${k}`, v));
  for (const [k, v] of Object.entries(scales.target)) out.push(decl(`target-${k}`, v));
  for (const [alias, target] of Object.entries(legacyAliases)) out.push(decl(alias, `var(--${target})`));
  return out.join('\n');
}

// Dark is the default. Light is opt-in through data-theme="light" (set by the theme switch / theme-init.js);
// the OS preference is not read implicitly, so the product looks the same everywhere until the user chooses.
const css = `/* Generated by packages/design-tokens (pnpm build). Do not edit. */
:root {
${scaleBlock()}
${themeBlock('dark')}
}
:root[data-theme='light'] {
${themeBlock('light')}
}
:root[data-theme='dark'] {
${themeBlock('dark')}
}
`;
const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, 'tokens.css'), css);
console.log(`wrote dist/tokens.css (${css.length} bytes)`);
