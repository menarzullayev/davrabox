import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { themes } from './tokens.js';

const vars = (t: Record<string, string>) => Object.entries(t).map(([k, v]) => `  --${k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}: ${v};`).join('\n');

const css = `/* Generated by packages/design-tokens. Do not edit. */
:root {\n${vars(themes.dark)}\n  color-scheme: dark;\n}
@media (prefers-color-scheme: light) {\n  :root {\n${vars(themes.light).replace(/^/gm, '  ')}\n    color-scheme: light;\n  }\n}
:root[data-theme='dark'] {\n${vars(themes.dark)}\n  color-scheme: dark;\n}
:root[data-theme='light'] {\n${vars(themes.light)}\n  color-scheme: light;\n}
`;
const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, 'tokens.css'), css);
console.log('wrote dist/tokens.css');
